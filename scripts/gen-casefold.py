#!/usr/bin/env python3
"""Generate cards-spec's case-folding table and the corpus's casefold.json.

    python3 scripts/gen-casefold.py CaseFolding-16.0.0.txt

Labels are compared by Unicode full case folding (statuses C and F, no T),
pinned to ONE Unicode version inside cards-spec, never the toolchain's std
tables (SynapsCLI #447): the extension and the desk then fold identically,
whatever Rust built them.

Two outputs, from two implementations:
- crates/cards-spec/src/casefold.rs, from CaseFolding.txt (its SHA-256 is
  checked below);
- fixtures/casefold.json, from Python's own str.casefold, which must be on
  the same Unicode (Python 3.14 is 16.0.0). The script refuses to write
  either unless the two agree at every scalar value.
"""

import hashlib
import json
import sys
import unicodedata
from pathlib import Path

UNICODE = "16.0.0"
SOURCE_URL = f"https://www.unicode.org/Public/{UNICODE}/ucd/CaseFolding.txt"
SOURCE_SHA256 = "6f1f9c588eb4a5c718d9e8f93b782685e5c7fec872cf05e8e6878053599e09bb"
ROOT = Path(__file__).resolve().parent.parent


def table_from_ucd(path):
    raw = Path(path).read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != SOURCE_SHA256:
        sys.exit(f"{path}: sha256 {digest}, want {SOURCE_SHA256} ({SOURCE_URL})")
    folds = {}
    for line in raw.decode().splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        cp, status, mapping = (x.strip() for x in line.split(";")[:3])
        if status in ("C", "F"):
            folds[int(cp, 16)] = "".join(chr(int(x, 16)) for x in mapping.split())
    return folds


def table_from_python():
    if unicodedata.unidata_version != UNICODE:
        sys.exit(f"Python's Unicode is {unicodedata.unidata_version}, not {UNICODE}: use a Python on {UNICODE}")
    folds = {}
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        if c.casefold() != c:
            folds[cp] = c.casefold()
    return folds


def esc(s):
    return "".join(f"\\u{{{ord(c):x}}}" for c in s)


def write_rust(folds):
    entries = [f"('{esc(chr(cp))}', \"{esc(folds[cp])}\")," for cp in sorted(folds)]
    rows = [" ".join(entries[i : i + 6]) for i in range(0, len(entries), 6)]
    body = "\n".join(f"    {r}" for r in rows)
    out = f"""//! Generated by `scripts/gen-casefold.py` from `CaseFolding.txt` {UNICODE}. Do not edit.
//! Source: <{SOURCE_URL}>,
//! sha256 `{SOURCE_SHA256}`.
//!
//! Every scalar value whose full case fold (statuses C and F) is not itself,
//! sorted. Any other scalar value folds to itself.

/// The Unicode version of [`FOLDS`]: the corpus's (`fixtures/casefold.json`).
pub const UNICODE_VERSION: (u8, u8, u8) = ({UNICODE.replace(".", ", ")});

#[rustfmt::skip]
pub static FOLDS: [(char, &str); {len(folds)}] = [
{body}
];
"""
    (ROOT / "crates/cards-spec/src/casefold.rs").write_text(out)


def write_fixture(folds):
    doc = {
        "about": (
            "The key labels are compared by: Unicode full case folding (CaseFolding.txt statuses C and F, "
            "Python str.casefold), no other normalization, at the Unicode version below. Every scalar value "
            "listed folds to the listed string; every other scalar value folds to itself."
        ),
        "unicode": UNICODE,
        "generated_by": f"Python {sys.version.split()[0]} str.casefold (unicodedata {unicodedata.unidata_version})",
        "folds": {f"U+{cp:04X}": folds[cp] for cp in sorted(folds)},
    }
    (ROOT / "fixtures/casefold.json").write_text(json.dumps(doc, ensure_ascii=True, indent=1) + "\n")


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    ucd = table_from_ucd(sys.argv[1])
    py = table_from_python()
    if ucd != py:
        diff = sorted(set(ucd.items()) ^ set(py.items()))[:10]
        sys.exit(f"CaseFolding.txt and str.casefold disagree: {diff}")
    write_rust(ucd)
    write_fixture(py)
    print(f"{len(ucd)} folds at Unicode {UNICODE}")


if __name__ == "__main__":
    main()
